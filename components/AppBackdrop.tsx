"use client";

import { BG } from "@/lib/constants";
import { shade } from "@/lib/helpers";

// ★アプリ全体の背景(2026-08-03)。
//
// ■ 3つの並べ方
//   ブリーフ  … 画面幅いっぱい(100vw)を1辺とする正方形のグリッドを画面中心
//                から上下へ展開し、その各マスに内接する正円を置く。上下の
//                マスは画面からはみ出して切れる(そのほうが良い、という指定)。
//   タスク    … 上のグリッドをさらに四分割した細かいグリッド(1辺 25vw)で、
//                画面左の一列だけに「左下が角の扇形」を置く。他のマスは空。
//   ジャーナル… 同じ細かいグリッドの、すべてのマスに円を置く。
//
// ■ 地と図形(明度は2値)
// 地はアプリの BG より少し濃いグレー。図形のあるところだけがそれより**薄い**
// 1色。この2値しか使わない。
//
// ■ 遷移
// DOM は常に「細かいグリッドのマス」1枚 = div 1つ。**マスは一度も動かない。**
// 変わるのは大きさ(と角の丸め方)だけで、transform-origin を左上に置いて
// あるため、伸縮するのは右辺と下辺 ＝ **グリッドの境目そのもの**。
// だからアプリを移る動きは、「境目が滑って4つのマスが1つのマスにまとまり、
// そのマスに沿って円が現れる」という、グリッドに沿った変形になる。
//
// ■ ★マスの種類は3つしかない(性能の要)
// 48枚あるマスも、3アプリを通しての振る舞いで分けるとたった3種類:
//   a … 左の列で、粗いマスの左上にあたるマス(ブリーフでは4倍に育つ)
//   b … 左の列のそれ以外(ブリーフでは消える)
//   c … 左の列以外(タスクでもブリーフでも消える)
// 最初は48枚それぞれに個別の calc() をインラインで書いていたが、指を動かす
// たびに 48枚 x 5つの複雑な calc() を評価し直すことになり、横スワイプの
// long task が 55ms から 1034ms へ跳ね上がった。3つのクラス(globals.css の
// .bd-a/.bd-b/.bd-c)に畳んで共有し、インラインには位置だけを残してある。
// 角の丸めが動くのも左の列(12枚)だけで、残り36枚は常に真円のまま。
//
// ■ 指の動きと直結
// 進み具合は AppShell が書く2つのCSS変数(--appi / --dragn)から作った連続値
// ひとつ(--p)だけで決まる。JSは毎フレーム何も計算せず、Reactのレンダーも
// 1回も走らない。指を離した瞬間は --p が目的地へ飛ぶが、transition が
// 掛かっているので滑らかに追いつく。

// 細かいグリッド。1マス = 画面幅の1/4。
const COLS = 4;
// 粗いグリッド(ブリーフ)。1マス = 細かいマス4つぶん = 画面幅いっぱい。
const BIG = 4;
const BIG_ROWS = 3;
// ★細かいグリッドの行数は粗いグリッドのちょうど4倍にする。どちらも画面中心を
// 軸に上下へ展開するので、行数がこの関係のときだけ**2つのグリッドの境目が
// 完全に重なる**(細かい4マスがちょうど粗い1マスに収まる)。ずれていると、
// 大きくなる途中でマスがグリッドから外れて見える。
const ROWS = BIG_ROWS * BIG;
const U = "25vw";

// 地と図形。地はアプリのBGより少しだけ濃いグレー、図形はそれより薄い。
// 「背景がグレーで、図形があるところが薄い」という指定どおりの向き。
const GROUND = shade(BG, -4);
const MARK = shade(BG, 3);

export function AppBackdrop() {
  const cells = [];
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      // 左の列(タスクの扇形が並ぶ列)か、そのうち粗いマスの左上にあたるか。
      const left = c === 0;
      const kind = left ? (r % BIG === 0 ? "a" : "b") : "c";
      cells.push(
        <div key={`${c}-${r}`} className={`app-backdrop-cell bd-${kind} ${left ? "bd-fan" : "bd-round"}`} style={{
          left: `calc(${U} * ${c})`,
          // 細かいグリッドは画面中心を軸に上下へ展開する(はみ出して構わない)。
          top: `calc(50svh - ${U} * ${ROWS / 2 - r})`,
          background: MARK,
        }} />
      );
    }
  }
  return (
    <div aria-hidden style={{
      position: "absolute", inset: 0, overflow: "hidden", pointerEvents: "none",
      // 呼び出し元(シェル)に isolation:isolate を与えてあるので、-1にしても
      // シェルの外へ抜け落ちない。0のままだと、CSSの描画順の規則により
      // 通常フローの中身(タブの本文)より後に描かれて文字を覆ってしまう。
      zIndex: -1, background: GROUND,
    }}>
      <div className="app-backdrop-grid" style={{ position: "absolute", inset: 0 }}>{cells}</div>
    </div>
  );
}
