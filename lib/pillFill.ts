/**
 * ★★★**帯のピルの「半透明の塗り」の作り方はここ1つ**（2026-09-23・第127巡に
 * ユーザー指定「**帯のハーフトーンもやめてください。代わりに半透明の塗りに
 * 文字にしてください**」）。
 *
 * ★★★**「半透明」を α ではなく混色で作る** ―― ピルは **DOM（帯）** と
 *   **canvas（引き下ろしの幽霊。`components/home/pillGhost.ts`）** の2つの技術で
 *   描かれ、**1px でも下へ引いた瞬間に DOM から canvas へ写し取る**。
 *   α のままだと、DOM 側は「親の地 → ピル → 文字」の順に重なるのに対し、
 *   canvas 側は**山の絵の上に重なる**ので、**その瞬間に色が変わる**。
 *   地は不透明の1色（`groundOf("home")`）と分かっているので、
 *   **先に混ぜてしまえば両方が厳密に同じ不透明色を塗る。**
 *
 * ★★★**第126巡のハーフトーン（`lib/halftone.ts`）は削除した。復活させない。**
 *   `HT_STEP`/`HT_DOT`/`PILL_KNOCK`（文字の周りの抜き）も一緒に消えている ――
 *   平らな面の上なら字が点と噛み合わないので、**抜きそのものが要らない**。
 */

import { mixHex } from "./constants";

/**
 * 塗りの濃さ。★目盛りの外（絵の刻み）。
 *
 * ★★**0.42 を選んだ理由は「面としては見え、字は読める」の両立**（実測。地 `#F7F6FB`）…
 *   地との比 … 青 **1.21** ／ 黄 **1.00** ／ オレンジ **1.32** ／ 赤 **1.59**、
 *   その上の墨の字 … **8.68 〜 13.82**（ベタ塗りだと赤で 4.77 まで落ちる）。
 * ★★**黄だけは地との比が 1.00**（＝明度が地とまったく同じ）だが、**彩度では
 *   はっきり違う**ので面として読める ―― 第126巡から同じ性質で、`lib/constants.ts`
 *   の `PALETTE` の注釈に書いてある。★形は**縁の線**が保証する。
 */
export const PILL_ALPHA = 0.42;

/**
 * ★**ピルの面の色**（不透明）。`face` を `ground` の上に `PILL_ALPHA` で重ねた色。
 * ★★**DOM も canvas もこの1つを読む**（`backgroundColor` と `ctx.fillStyle`）。
 */
export const pillFillOf = (face: string, ground: string): string =>
  mixHex(ground, face, PILL_ALPHA);
