/**
 * ★★★**掴んだ一点だけが垂れる山**（2026-09-14・第105巡にユーザー確定
 * 「**両端は帯に残る**」＝**輪ゴムを引っ張る**）。
 *
 * `bump` は掴んだ点で 1、**ピルの左右の端でちょうど 0** になる `cos²` の山。
 * ★★**端が厳密に 0 だからこそ「帯に残っている」が形で言える** ―― ここが
 *   「ピルがそこに止まろうとするような抵抗」の正体で、**抵抗を数で足していない。**
 *
 * @param dx    ピルの中心から見た、測りたい点の x
 * @param gx    ピルの中心から見た、掴んだ点の x
 * @param reach 端までの距離（＝ピルの半幅）。ここで 0 になる
 * @param give  掴んだ点が垂れる量（px）
 * @param w     上下の重み（下の縁 1 ／上の縁 `BEND_TOP`）
 */
export function bendAt(
  dx: number, gx: number, reach: number, give: number, w: number,
): number {
  const u = Math.min(1, Math.abs(dx - gx) / Math.max(1, reach));
  const c = Math.cos((Math.PI / 2) * u);
  return give * c * c * w;
}

export interface PullFrame {
  /** 器の座標での中心（`armed` なら指、まだなら**ピルの中心のまま**）。 */ cx: number; cy: number;
  /** ゴムを抜けて指に付いているか（＝離したら日付が付く段階か）。 */ armed: boolean;
  /** 下へ引いた量（px）。★**1px でも引いたら写し取りに切り替える**。 */ pulled: number;
  /** ★`armed` の前 … 掴んだ点が垂れている量（px）。 */ bend: number;
}

/**
 * ★★★**指の位置から、幽霊の「いま」を出す**（純粋な関数）。
 *
 * @param fx,fy   いまの指（器の座標）
 * @param sy      掴んだ瞬間の指の y（器の座標）
 * @param bx,by   掴んだピルの中心（器の座標）
 *
 * ★★★**弾ける前はピルは1px も動かない**（2026-09-14・第105巡にユーザー確定
 *   「**両端は帯に残る**」）。動くのは**掴んだ一点の垂れ**（`bend`）だけで、
 *   その形が「ピルがそこに止まろうとするような抵抗」をそのまま言う。
 * ★★越えると `t` が育ち、**目標が指そのもの**になる（そこへ**バネで追いつく**
 *   ―― `stepGhost`）。★同じ `t` が形の変形も動かすので、
 *   「変わりながら吸い付く」が1つの数から出る。
 */
export function pullFrame(
  fx: number, fy: number, sy: number, bx: number, by: number,
): PullFrame {
  const dy = fy - sy;
  // ★下へ引いたぶんだけを見る（上へ戻せば 0 に近づく）。
  const pulled = Math.max(0, dy);
  // ★★**垂れる量は `rubber`**（閾値で傾き 1 ＝ 継ぎ目が無い）。上限は
  //   `PULL_ARM × PULL_GIVE × PULL_RESIST` ＝ 28.8px で、**式から出る**
  //   （生の上限を別に置かない）。★横へ引いたぶんは見ない ―― 輪ゴムは
  //   **指の下へ垂れる**のであって、横へは端が留めている。
  const give = rubber(pulled / PULL_ARM, PULL_GIVE) * PULL_ARM * PULL_RESIST;
  const armed = pulled > PULL_ARM;
  return {
    // ★★★**弾けたら目標は指そのもの**（2026-09-14・第104巡にユーザー確定
    //   「**ばちんという感じで弾けて指に吸い付く**」）。★第105巡から、ここへ
    //   **飛ばずにバネで追いつく**（`stepGhost` の `catchX`/`catchY`）。
    // ★★★**弾ける前はピルは動かない**（第105巡にユーザー確定「**両端は帯に残る**」）。
    //   第104巡は `gx`/`gy` でピルごと下げていたが、それだと**輪ゴムではなく
    //   引き出し**に見える。動くのは**掴んだ一点だけ**（`bend`）。
    cx: armed ? fx : bx,
    cy: armed ? fy : by,
    armed,
    pulled,
    bend: give,
  };
}

/** 右の縁から何 px で ASSIGN の帯が出るか。★目盛りの外（手ざわり）。 */
export const RAIL_NEAR = 72;
/**
 * ★★★**帯の境目の「遊び」**（2026-09-16・第108巡）。★目盛りの外（手ざわり）。
 *
 * ★★**入るのは `RAIL_NEAR`、出るのは `RAIL_NEAR + RAIL_HYST`。**
 *   境目を1本の線にすると、**指がその線の上に居るあいだ毎フレーム
 *   「入った／出た」が反転**し、変形の行き先（`tTo`）が 1 と 0 を往復して
 *   形がぶるぶる震える（ユーザー報告「動作がやっぱり不安定」）。
 * ★ピル1つぶんの高さ（`PULL_ARM`）の半分 ＝ 指が意図して動かす量。
 */
export const RAIL_HYST = PULL_ARM / 2;
/**
 * ★★★**姿の掛け金が「図形」へ戻る境目**（2026-09-16・第108巡）。★目盛りの外（変形の進み）。
 * ★変形のばね（`K_CATCH`/`D_CATCH`）の行き過ぎは **16%** なので、それより**広く**取る。
 *   狭いと行き過ぎの底で掛け金が外れ、また点滅する。
 */
export const PILL_EXIT = 0.2;

// ── ぶら下がりと伸び縮み（2026-09-14・第103巡にユーザー確定） ─────────────
//
// ★★★**ユーザーの指定は2つだけ** … 「**指にぶら下がって揺れる**」と
//   「**引く速さで伸び縮みする**」。★「糸を引いて千切れる」「着地で山が沈む」は
//   **採らない**と確定した。**勝手に足さないこと。**
//
// ★★★**バネは `Pile.tsx` のループが回す。指のイベントでは進めない**
//   ―― `pointermove` の間隔は端末任せ（実機で 8〜30ms にばらつく）なので、
//   そこで1歩ずつ進めると**同じ手つきでも日によって手ざわりが変わる**。
//   物理と同じ**固定の刻み**で回せば、`lib/spring.ts` の係数がそのまま効く。

/** 支点が中心から上の縁へ移りきる `t`。★目盛りの外（手ざわり）。 */
export const HANG_T = 0.6;
/** 振れの上限（rad ≒ 22°）。★目盛りの外（手ざわり）。 */
export const SWING_MAX = 0.38;
/** 振れが上限に届く指の速さ（px/フレーム）。★同上。 */
const SWING_V = 18;
/** 伸びの上限（1 ＋ これ が長いほうの倍率）。★目盛りの外（手ざわり）。 */
export const STRETCH_MAX = 0.22;
/** 伸びが上限に届く指の速さ（px/フレーム）。★同上。 */
const STRETCH_V = 34;

/** 幽霊のバネ（3本）。★`Pile.tsx` が1つだけ持ち、幽霊が消えたら捨てる。 */
export interface GhostMotion {
  /** 前のフレームの中心（速さを出すため）。 */
  px: number; py: number;
  had: boolean;
  swing: Spring;
  /** 伸びの量（0〜`STRETCH_MAX`）。 */
  pull: Spring;
  /** 伸びる向き（rad）。★**速さの向き**なので、バネではなく直に持つ。 */
  dir: number;
  /** ★★★**変形のばね**（0 → 1 へ一息で開き、行き過ぎてから収まる）。 */
  morph: Spring;
  /**
   * ★★★**追いつき**（2026-09-14・第105巡）。弾けた所から**指へ寄っていく支点**。
   * ★★**弾けた瞬間に「弾ける前の支点」で種を蒔く**（`caught`）―― 種を蒔かないと
   *   バネが原点から走り出して、画面の左上から飛んでくる。
   */
  catchX: Spring; catchY: Spring; caught: boolean;
}

export const ghostMotion = (): GhostMotion => ({
  px: 0, py: 0, had: false, swing: spring(), pull: spring(), dir: Math.PI / 2,
  catchX: spring(), catchY: spring(), caught: false, morph: spring(),
});

/** −1〜1 へ滑らかに丸める（頭打ちで角が立たない）。 */
const soft = (v: number, at: number): number => Math.tanh(v / Math.max(1e-6, at));

/** 投げの上限（px/フレーム）。★これを超えると壁を貫通する。★目盛りの外（物理の場）。 */
const THROW_MAX = 18;
const clampV = (v: number): number => Math.max(-THROW_MAX, Math.min(THROW_MAX, v));

/**
 * ★★★**幽霊を1フレームぶん動かす**（`g` を直接書き換える）。
 *
 * ・**ぶら下がり** … 支点は `t` に連れて**中心 → 上の縁**へ移る（`HANG_T` で移りきる）。
 *   振れの目標は**指の横の速さ**から。★`K_TRAVEL`/`D_TRAVEL` は**わずかに行き過ぎる**
 *   ので、指を止めると**揺り返して**から静かに戻る ＝ 重いものを摘まんでいる感触。
 * ・**伸び縮み** … 速さの**向き**へ伸びる。★**積を 1 に保つ**（`sx·sy = 1`）ので、
 *   伸びても**大きさは変わって見えない** ―― 変わると「育った」に見えてしまう。
 */
export function stepGhost(mo: GhostMotion, g: Ghost): void {
  const vx = mo.had ? g.cx - mo.px : 0;
  const vy = mo.had ? g.cy - mo.py : 0;
  mo.px = g.cx; mo.py = g.cy; mo.had = true;

  // ★★★**変形は「時間」で進む**（2026-09-15・第106巡にユーザー確定）。
  //   ★★**指の距離では進めない** ―― 第105巡までは `MORPH_SPAN`(90px) で、
  //     「どこまで引いたか」で段の数が変わっていた（ユーザー「**不自然**」）。
  //   ★★**`tTo` を 0 にすればそのまま逆再生**になる（帯へ戻すときに使う）。
  //   ★この関数は**山のループの固定の刻み**（`STEP_MS`）で呼ばれるので、
  //     60Hz でも 120Hz でも同じ速さで変形する。
  // ★★★**ばね1本で一息に開く**（2026-09-16・第107巡）。行き過ぎてから収まるので、
  //   **くびれが最終より一度深く入って戻る＝ぱんと開く**。
  //   ★★`tTo` を 0 にすれば**そのまま逆再生**（帯へ戻すときに使う）。
  springTo(mo.morph, g.tTo, K_CATCH, D_CATCH);
  g.t = mo.morph.p;
  g.w = g.w0 + (g.w1 - g.w0) * g.t;
  g.h = g.h0 + (g.h1 - g.h0) * g.t;
  // ★くびれは 0〜1 に収める（形の式はその外を知らない）。行き過ぎは**箱**に出る。
  g.waist = Math.max(0, Math.min(1, g.t));
  // ★★★**姿の掛け金**（2026-09-16・第108巡。`Ghost.pill` の説明を参照）。
  //   **落ちるのは 0、戻るのは `PILL_EXIT`。** ばねが 0 を跨いでも姿は変わらない。
  if (g.t <= 0) g.pill = true;
  else if (g.t >= PILL_EXIT) g.pill = false;

  // ★★★**帯へ戻すときは、掴んでいる体がもう指に付いている**（2026-09-15・第106巡）。
  //   ★★だから振れも伸びも追いつきのバネも掛けない ―― **二重に掛けると、絵だけが
  //     体から離れて泳ぐ**。ここでするのは「形を畳む」ことと「起き上がる」ことだけ。
  //   ★★**角度は `t` に連れて 0 へ**（帯のピルは真っ直ぐ立っている）。転がっていた
  //     図形が**ピルに戻りながら向きを正す**ので、吸い込まれるように見える。
  if (g.home) {
    g.angle *= g.waist;
    // ★★★**支点も毎フレーム体へ置く**（2026-09-16・第108巡）。
    //   ★★★**絵は `hx`/`hy` に描かれる**（`components/home/pilePaint.ts` の
    //     `ctx.translate(g.hx, g.hy)` と `components/home/pillGhost.ts` の同じ行）。
    //     第107巡までここで `dx`/`dy` しか書いていなかったので、**幽霊は
    //     逆変形を始めた場所に貼り付いたまま1px も動かなかった**
    //     ―― ユーザー報告「**途中で図形がそこより上に行かなくなって止まって、
    //     そのピルのところに戻すことができませんでした**」はこれそのもの。
    //   ★体はすでに指へバネで寄っている（`Pile.tsx` の `GRAB_K`）ので、
    //     **ここでバネを二重に掛けない**。
    g.hx = g.cx; g.hy = g.cy;
    g.ax = 0; g.ay = 0; g.dx = g.cx; g.dy = g.cy;
    g.sx = 1; g.sy = 1; g.vx = 0; g.vy = 0;
    return;
  }

  // ★★★**ピルの姿のあいだは帯の写し取り**（2026-09-14・第105巡にユーザー確定
  //   「**両端は帯に残る**」）。ピルは動かず、**掴んだ一点だけが垂れる**ので、
  //   振れも伸び縮みもぶら下がりも**まだ起きない**。★支点はピルの中心そのもの。
  //   ★★**帯へ戻すときはここへ来ない**（指に付いて運ばれている最中なので）。
  if (g.pill && !g.home) {
    mo.caught = false;
    g.hx = g.cx; g.hy = g.cy;
    g.ax = 0; g.ay = 0; g.dx = g.cx; g.dy = g.cy;
    g.angle = 0; g.sx = 1; g.sy = 1;
    g.vx = 0; g.vy = 0;
    // ★弾みの注文は捨てずに残す（弾けた最初のフレームで受け取る）。
    return;
  }

  // ★★★**弾けた所から指へ「追いつく」**（2026-09-14・第105巡にユーザー指定
  //   「**一気に指の方に全体が滑らかにアニメーションしながら吸い付いて揺れる**」）。
  //   第104巡は支点を指へ**瞬間移動**させていたので、滑らかでも揺れてもいなかった。
  //   ★`K_CATCH` は 16% 行き過ぎるので、**指を追い越してから戻る**＝吸い付く。
  if (!mo.caught) {
    mo.caught = true;
    mo.catchX.p = g.hx; mo.catchX.v = 0;
    mo.catchY.p = g.hy; mo.catchY.v = 0;
  }
  springTo(mo.catchX, g.cx, K_CATCH, D_CATCH);
  springTo(mo.catchY, g.cy, K_CATCH, D_CATCH);
  g.hx = mo.catchX.p; g.hy = mo.catchY.p;
  // ★★離した瞬間に物理へ渡す（`Landing`）のは**支点の速さ**（＝実際に絵が動いて
  //   いる速さ）。指の速さだと、追いついている最中に離したときに**絵より速く**飛ぶ。
  //   ★**単位は px/フレーム**で、matter.js の刻みも 1000/60 固定なので同じ意味。
  g.vx = clampV(mo.catchX.v); g.vy = clampV(mo.catchY.v);

  // ★★**支点は指そのもの。図形はその下へぶら下がる**（`t` が育つほど深く）。
  //   ★指が図形の**上の縁**を摘まんでいる形になるので、回る中心が上に在る
  //   ＝「ぶら下がっている」に見える。中心を指に置くと、ただ回るだけに見えた。
  const hang = Math.min(1, g.t / HANG_T);
  g.ax = 0;
  g.ay = (g.h / 2) * hang;
  // ★★★**振れは指の動きに「遅れる」**（符号が負）。指を右へ動かせば、ぶら下がった
  //   ものは**左へ残る** ―― 正のままだと先回りして、引きずられている感じが出ない。
  springTo(mo.swing, -soft(vx, SWING_V) * SWING_MAX * hang, K_SWING, D_SWING);
  g.angle = mo.swing.p;
  const ca = Math.cos(g.angle); const sa = Math.sin(g.angle);
  g.dx = g.hx + g.ax * ca - g.ay * sa;
  g.dy = g.hy + g.ax * sa + g.ay * ca;

  // ★伸び … 速さの大きさで量、速さの向きで軸。止まっている間は向きを変えない
  //   （0 に近い速さの向きは雑音なので、拾うと図形が小刻みに回る）。
  const sp = Math.hypot(vx, vy);
  if (sp > 0.5) mo.dir = Math.atan2(vy, vx);
  springTo(mo.pull, soft(sp, STRETCH_V) * STRETCH_MAX, K_SWING, D_SWING);
  // ★★**縮みも許す**（ユーザー確定は「伸び**縮み**」）。バネが行き過ぎるので、
  //   止めた瞬間に**伸びたぶんの反対**へ一度潰れてから戻る ＝ 弾力のある物体。
  //   ★潰れは伸びの半分まで（潰れ過ぎると別の形に見える）。
  const e = Math.max(-STRETCH_MAX / 2, Math.min(STRETCH_MAX, mo.pull.p));
  g.sx = 1 + e;
  g.sy = 1 / (1 + e);
  // ★伸びの軸は**振れとは別**なので、描く側で `dir` ぶん回してから伸ばす。
  g.stretchDir = mo.dir;
}

